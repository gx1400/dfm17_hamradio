#!/bin/bash
# format.sh [check|fix] [BASE]: clang-format on the C lines changed since BASE
# (default origin/main), in our own sources only. The STM32CubeMX generated
# files and the vendor drivers are never formatted, and code nobody touches
# isn't reformatted: the style converges as files are edited.
#
#   tools/lint/format.sh check    exit 1 and show the diff if changed lines
#                                 don't match .clang-format (what CI runs)
#   tools/lint/format.sh fix      reformat the changed lines in the work tree;
#                                 stage your changes first (git add), as
#                                 git clang-format only formats staged files
#
# Needs clang-format and git-clang-format (pip install -r tools/requirements-lint.txt).
cd "$(dirname "$0")/../.." || exit 1
MODE=${1:-check}
BASE=${2:-origin/main}

# same list as tools/lint/check_eol.sh: generated by STM32CubeMX
generated='^dfm17/Core/(Src|Inc)/(main|dma|gpio|spi|tim|usart|stm32f1xx_it|stm32f1xx_hal_msp|system_stm32f1xx|stm32f1xx_hal_conf)\.[ch]$'
mapfile -t files < <(git ls-files 'dfm17/Core/*.c' 'dfm17/Core/*.h' 'tools/*.c' 'tools/*.h' \
	| grep -Ev "$generated")

case "$MODE" in
check)
	out=$(git clang-format --diff --extensions c,h "$BASE" -- "${files[@]}" 2>&1)
	case "$out" in
	"" | "no modified files to format" | *"did not modify any files"*)
		echo "clang-format: changed lines OK"; exit 0 ;;
	esac
	echo "$out"
	echo "clang-format: changed lines don't match .clang-format; run tools/lint/format.sh fix" >&2
	exit 1 ;;
fix)
	git clang-format --extensions c,h "$BASE" -- "${files[@]}" ;;
*)
	sed -n '2,14p' "$0" | sed 's/^# \{0,1\}//'; exit 2 ;;
esac
